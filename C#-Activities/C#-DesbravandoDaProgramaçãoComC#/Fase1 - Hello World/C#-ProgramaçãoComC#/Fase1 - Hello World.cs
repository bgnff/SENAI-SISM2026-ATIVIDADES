using System; // A instrução "using" importa a biblioteca necessária para usar o Console.

class Fase1 // Definimos uma classe chamada "Fase1". Em C#, a execução do código
{
    static void Main(string[] args) // O método "Main" é o ponto de entrada do programa. É onde a execução do código começa.
    {
        Console.WriteLine("Hello, World!"); // Exibe a mensagem "Hello, World!" no console.

        Console.ReadLine(); // Aguarda o usuário pressionar Enter antes de encerrar o programa.
    }
}